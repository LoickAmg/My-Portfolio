"use client";

// Dictionnaire de traduction centralisé (FR par défaut, EN en option) —
// sélecteur client sans routing par URL (voir useLanguage.ts). Un seul
// fichier plutôt qu'un fichier par section : le volume total reste
// raisonnable pour un site vitrine, et ça évite d'avoir à chercher dans dix
// fichiers pour retrouver une chaîne.
//
// Convention : chaque section du site a sa propre clé, dans le même ordre
// que les composants qui la consomment. `useT()` renvoie à la fois la
// langue active (pour les cas qui ont besoin de brancher sur autre chose,
// ex. Intl.NumberFormat) et l'objet de traduction déjà résolu.

import { useLanguage, type Lang } from "./useLanguage";

